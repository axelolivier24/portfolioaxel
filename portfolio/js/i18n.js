let currentLang = (function () {
  try { return localStorage.getItem("tkao_lang") || "fr"; }
  catch (e) { return "fr"; }
})();

function setLanguage(lang) {
  if (!translations[lang]) lang = "fr";
  currentLang = lang;
  try { localStorage.setItem("tkao_lang", lang); } catch (e) { /* stockage indisponible */ }
  document.documentElement.lang = lang;

  const langBtn = document.getElementById("langToggle");
  if (langBtn) langBtn.textContent = lang === "fr" ? "EN" : "FR";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key] !== undefined) el.textContent = translations[lang][key];
  });

  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (translations[lang][key] !== undefined) el.setAttribute("placeholder", translations[lang][key]);
  });

  // Les libellés de la modale ouverte (si ouverte) suivent la langue
  const modalLink = document.getElementById("modalLink");
  if (modalLink) {
    const span = modalLink.querySelector("span[data-i18n='btnCode']");
    if (span) span.textContent = translations[lang].btnCode;
  }

  // La mise en page pouvant changer (longueurs de textes), on rafraîchit ScrollTrigger
  // et on prévient le moteur d'animation (redécoupe des titres en lettres).
  document.dispatchEvent(new CustomEvent("tkao:lang", { detail: { lang: lang } }));
  if (window.ScrollTrigger) window.ScrollTrigger.refresh();
}
